#!/usr/bin/env python3
"""Converts tombatossals/chords-db's guitar.json (MIT) into the compact table
`crates/cpl-song/data/guitar.tsv`: one line per chord, first position only,
which is the only one the viewer uses.

    python3 -I scripts/chords-from-json.py ~/src/chordpro-tui/internal/chords/guitar.json

Columns: key, suffix, base fret, frets (-1 muted), fingers (0 none), barres;
lists are space-separated. The JSON came to this project through
chordpro-tui/internal/chords/guitar.json.
"""
import json
import sys

source = json.load(open(sys.argv[1]))
out = open("crates/cpl-song/data/guitar.tsv", "w")
out.write("# Guitar chord shapes from tombatossals/chords-db (MIT licence,\n")
out.write("# https://github.com/tombatossals/chords-db), first position of each chord.\n")
out.write("# Generated by scripts/chords-from-json.py; do not edit by hand.\n")
out.write("# key\tsuffix\tbase_fret\tfrets\tfingers\tbarres\n")
count = 0
for key, entries in source["chords"].items():
    for entry in entries:
        if not entry["positions"]:
            continue
        p = entry["positions"][0]
        row = [
            key,
            entry["suffix"],
            str(p.get("baseFret", 1)),
            " ".join(str(f) for f in p["frets"]),
            " ".join(str(f) for f in p.get("fingers", [0] * len(p["frets"]))),
            " ".join(str(b) for b in p.get("barres", [])),
        ]
        out.write("\t".join(row) + "\n")
        count += 1
print(f"{count} chords written")
